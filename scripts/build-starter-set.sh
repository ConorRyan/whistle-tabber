#!/usr/bin/env bash
# Builds app/src/main/assets/tunes/oneills.abc, the starter set offered on an
# empty library, from the O'Neill's Project transcriptions of O'Neill's Music
# of Ireland (1850) (GPL-2+, credits kept in each tune's Z: and B: lines).
#
# The tune list and the R: value for each tune are in scripts/starter-tunes.txt.
# Each tune is copied as published except that its R: line is set from the list
# (many 1850 transcriptions have none), a list-given Z: credit is added to a
# tune that has none, and trailing spaces are dropped.
#
# The build does not run this; its output is committed. Run it after editing
# the list, then run the unit and node tests (they check every tune).
#
# Run: scripts/build-starter-set.sh
set -euo pipefail

BASE="https://trillian.mit.edu/~jc/music/book/ONeills/_1850/X"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LIST="$ROOT/scripts/starter-tunes.txt"
DEST="$ROOT/app/src/main/assets/tunes/oneills.abc"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

{
    echo "% Whistle Tabber starter set: tunes from O'Neill's Music of Ireland (1850)."
    echo "% ABC transcriptions (c) 1997-2000 the contributors to the O'Neill's Project,"
    echo "% $BASE/"
    echo "% Licensed under the GNU GPL, version 2 or later. Transcribers are credited"
    echo "% in each tune's Z: lines. Generated by scripts/build-starter-set.sh, which"
    echo "% sets each tune's R: line; the music is unchanged."
} > "$TMP/out.abc"

count=0
while IFS='|' read -r file rhythm _title credit; do
    [[ "$file" =~ ^[[:space:]]*(#|$) ]] && continue
    file="${file//[[:space:]]/}"
    rhythm="$(sed -E 's/^[[:space:]]+|[[:space:]]+$//g' <<< "$rhythm")"
    credit="$(sed -E 's/^[[:space:]]+|[[:space:]]+$//g' <<< "$credit")"

    curl -fsSL "$BASE/$file" -o "$TMP/raw.abc"
    if ! iconv -f UTF-8 -t UTF-8 "$TMP/raw.abc" > "$TMP/tune.abc" 2>/dev/null; then
        iconv -f ISO-8859-1 -t UTF-8 "$TMP/raw.abc" > "$TMP/tune.abc"
    fi

    # First tune only (it ends at a blank line); R: set after the last T: line;
    # the list's credit added before K: when the tune has no Z: line.
    awk -v rhythm="$rhythm" -v credit="$credit" '
        { sub(/\r$/, ""); sub(/[ \t]+$/, "") }
        /^X:/ { started = 1 }
        !started { next }
        started && /^$/ { exit }
        /^R:/ { next }
        /^Z:/ { hasZ = 1 }
        { lines[n++] = $0; if (!inbody && /^T:/) lastT = n - 1; if (!inbody && /^K:/) { key = n - 1; inbody = 1 } }
        END {
            if (n == 0) exit 1
            for (i = 0; i < n; i++) {
                if (i == key && !hasZ && credit != "") print "Z:" credit
                print lines[i]
                if (i == lastT) print "R:" rhythm
            }
        }
    ' "$TMP/tune.abc" > "$TMP/clean.abc" || { echo "no tune in $file" >&2; exit 1; }

    { echo; cat "$TMP/clean.abc"; } >> "$TMP/out.abc"
    count=$((count + 1))
    sleep 0.2 # be gentle with the O'Neill's Project server
done < "$LIST"

mkdir -p "$(dirname "$DEST")"
mv "$TMP/out.abc" "$DEST"
echo "Wrote $count tunes to $DEST"
